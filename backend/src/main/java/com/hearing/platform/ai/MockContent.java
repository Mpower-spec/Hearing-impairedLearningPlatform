package com.hearing.platform.ai;

/**
 * 模拟内容（降级兜底）。
 * 当 AI 模式为 mock 或 auto 下真实调用失败时，提供与真实输出同构的
 * Markdown 示例内容，保证演示流程不依赖外部模型也能走通。
 */
public final class MockContent {

    // 私有构造，禁止实例化（纯静态内容类）
    private MockContent() {
    }

    // 备课资料的模拟输出（与 PromptTemplates.prepare 要求的标题结构一致）
    public static String prepare(String lessonTitle) {
        return """
                # %s · 备课资料（演示兜底）

                ## 教学目标
                - 理解本节课的核心概念及基本应用。
                - 能用自己的语言复述关键知识点。
                - 通过练习发现并修正常见误区。

                ## 重点与难点
                - 重点：核心概念的识别与解释。
                - 难点：把概念迁移到新的情境中。

                ## 知识点提纲
                1. 概念导入
                2. 核心原理
                3. 示例分析
                4. 课堂练习与总结

                ## 术语解释
                - **核心概念**：本节课需要重点理解的基础知识。
                - **迁移应用**：在新问题中使用已学知识。

                ## 课堂提问
                - 你能举出一个生活中的相关例子吗？
                - 如果条件发生变化，结论是否仍然成立？

                ## 随堂练习
                1. 用自己的话解释核心概念。
                2. 完成一道基础应用题并说明思路。
                """.formatted(lessonTitle);
    }

    // 课堂学习资料的模拟输出
    public static String classMaterial(String lessonTitle) {
        return """
                # %s · 课堂学习资料（演示兜底）

                ## 课堂摘要
                本节课围绕核心概念展开，通过讲解、示例和互动帮助学生建立完整理解。

                ## 重点内容
                - 核心概念的定义与判断方法。
                - 典型例题的解题步骤。
                - 常见错误与检查方式。

                ## 术语表
                | 术语 | 解释 |
                | --- | --- |
                | 核心概念 | 本节课的基础知识 |
                | 示例 | 用于说明概念的具体情境 |

                ## 复习问题
                1. 本节课最重要的概念是什么？
                2. 如何判断一个例子是否符合所学规律？

                ## 简单测验
                1. 请写出核心概念的定义。
                   **参考答案：** 根据课堂内容准确表述即可。
                2. 举一个新例子说明概念的应用。
                   **参考答案：** 例子合理并能说明对应关系即可。
                """.formatted(lessonTitle);
    }

    public static String courseQa(String question, String sourceExcerpt) {
        return "当前为演示模拟回答。针对问题“" + question + "”，检索到的相关课程内容是："
                + sourceExcerpt + " [S1]\n\n配置真实 AI 服务后可获得更完整的分析与解释。";
    }
    // 视频学习笔记的模拟输出
    public static String videoNote(String title) {
        return """
                # %s · 学习笔记（演示兜底）

                ## 视频摘要
                视频围绕一个核心主题展开，依次介绍背景、关键概念和应用示例。

                ## 内容时间线
                - 开头：介绍学习目标与背景。
                - 中段：解释核心概念并分析示例。
                - 结尾：总结重点并布置复习任务。

                ## 核心概念
                - 核心概念的定义
                - 概念之间的因果关系
                - 在实际问题中的使用方式

                ## 易错点
                - 混淆相近概念。
                - 只记住结论而忽略适用条件。

                ## 复习清单
                - [ ] 复述视频的主要结论
                - [ ] 整理三个关键词
                - [ ] 完成一次自我提问
                """.formatted(title);
    }

    // 视频转写文本的模拟输出（供 ASR 降级时使用）
    public static String transcript() {
        return "同学们，今天我们来学习本节课的核心内容。首先理解基本概念，然后通过一个例子观察概念之间的关系。"
                + "请大家注意，应用知识时要先判断条件，再选择合适的方法。最后，我们回顾重点，并完成一道复习题。";
    }
}
